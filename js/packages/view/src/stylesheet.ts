/**
 * The optional default stylesheet, generated for a prefix.
 *
 * **The requirement it is written against: it must style the HTML emitter's
 * output untouched.** A saved report from `handle.emit('html')` and the
 * virtualized view are the same diff and must not look like two products, and
 * spec 13.3 makes them the same cursor, so making them the same stylesheet costs
 * one file and buys the guarantee. Everything the view needs beyond what the
 * emitter writes is expressed as a `data-` attribute, so every selector below
 * either applies to both documents or is qualified by an attribute only one of
 * them carries.
 *
 * It is a function of the prefix rather than a static file because the prefix is
 * configurable per component, per spec 13.0, and a consumer who changes it would
 * otherwise have to hand write the whole sheet. `styles/*.css` in this package
 * are this function's output for the default prefix, generated by
 * `scripts-and-commands/gen_stylesheet.mjs` and checked in the gate, so the file
 * a bundler imports and the string this returns cannot drift.
 *
 * Two decisions worth defending:
 *
 *   1. **`white-space: pre-wrap` on the cell class.** The emitter writes a cell's
 *      newline through unchanged and does not invent a `<br>`, which is right:
 *      inventing markup for data is how a report starts lying about its input. So
 *      the decision about what a newline looks like belongs here, in the
 *      stylesheet, and this is it. Without it a multiline CSV field collapses to
 *      one line and the diff appears to show a change that is not there.
 *
 *   2. **Colour is never the only signal.** Spec 8.5 calls this a correctness
 *      issue for colour blind reviewers rather than a nicety. The view renders a
 *      real marker cell; the emitter has no such element, so for its documents
 *      the same glyph comes from generated content on the row number gutter. The
 *      two are mutually exclusive by selector so no document gets both.
 */

import { assertClassPrefix, DEFAULT_CLASS_PREFIX } from './classes.ts';

export interface StylesheetOptions {
  prefix?: string;
  /** Emit the `:root` custom property defaults. Off gives structure only, for a
   *  consumer who supplies the whole palette from their own design tokens. */
  variables?: boolean;
}

